    for level in ('n2','n1'):
        file=DATA/('grammar-'+level+'.json')
        lessons=json.loads(file.read_text(encoding='utf-8'))
        index={x['id']:x for x in lessons}
        order=0
        for key,title,numbers in MODULES[level]:
            for num in numbers:
                order+=1;id=f'g-{level}-{num:03}'
                assert id in ENTRIES
                index[id]['textbook']=ENTRIES[id]
                index[id]['curriculum']={'program':'jlpt','chapterId':level,
                  'chapterTitle':'N2 · 综合运用' if level=='n2' else 'N1 · 深入理解',
                  'moduleId':level+'-'+key,'moduleTitle':title,'order':order}
        file.write_text(json.dumps(lessons,ensure_ascii=False,indent=2),encoding='utf-8')
        report[level]=sum('textbook' in x for x in lessons)
    print(report)

